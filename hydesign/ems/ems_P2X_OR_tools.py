def ems_OR_tools_P2X(
    wind_ts,
    solar_ts,
    price_ts,
    P_batt_MW,
    E_batt_MWh_t,
    hpp_grid_connection,
    battery_depth_of_discharge,
    charge_efficiency,
    price_H2,
    ptg_MW,
    HSS_kg,
    storage_eff,
    hhv,
    m_H2_demand_ts,
    H2_storage_t,
    penalty_factor_H2,
    eff_curve,
    min_power_standby,
    load_min_penalty_factor=1e6,
    peak_hr_quantile=0.9,
    cost_of_battery_P_fluct_in_peak_price_ratio=0.5,  # [0, 0.8]. For higher values might cause errors
    n_full_power_hours_expected_per_day_at_peak_price=3,
    batch_size=62,
    electrolyzer_eff_curve_type="production",
):

    # split in batches, ussually a week
    batches_all = split_in_batch(list(range(len(wind_ts))), batch_size)
    # Make sure the last batch is not smaller than the others
    # instead append it to the previous last one
    # batches = batches_all[:-1]
    # batches[-1] = batches_all[-2]+batches_all[-1]
    batches = batches_all

    # allocate vars
    P_HPP_ts = np.zeros(len(wind_ts))
    P_curtailment_ts = np.zeros(len(wind_ts))
    P_charge_discharge_ts = np.zeros(len(wind_ts))
    P_ptg_ts = np.zeros(len(wind_ts))
    P_ptg_SB_ts = np.zeros(len(wind_ts))
    m_H2_ts = np.zeros(len(wind_ts))
    m_H2_offtake_ts = np.zeros(len(wind_ts))
    LoS_H2_ts = np.zeros(len(wind_ts))
    E_SOC_ts = np.zeros(len(wind_ts) + 1)
    penalty_ts = np.zeros(len(wind_ts))

    for ib, batch in enumerate(batches):
        wind_ts_sel = wind_ts.iloc[batch]
        solar_ts_sel = solar_ts.iloc[batch]
        price_ts_sel = price_ts.iloc[batch]
        E_batt_MWh_t_sel = E_batt_MWh_t.iloc[batch]
        m_H2_demand_ts_sel = m_H2_demand_ts.iloc[batch]
        H2_storage_t_sel = H2_storage_t.iloc[batch]

        # print(f'batch {ib+1} out of {len(batches)}')
        (
            P_HPP_ts_batch,
            P_curtailment_ts_batch,
            P_charge_discharge_ts_batch,
            P_ptg_ts_batch,
            P_ptg_SB_ts_batch,
            E_SOC_ts_batch,
            m_H2_ts_batch,
            m_H2_offtake_ts_batch,
            LoS_H2_ts_batch,
            penalty_batch,
        ) = ems_OR_tools_parts_P2X(
            wind_ts=wind_ts_sel,
            solar_ts=solar_ts_sel,
            price_ts=price_ts_sel,
            P_batt_MW=P_batt_MW,
            E_batt_MWh_t=E_batt_MWh_t_sel,
            hpp_grid_connection=hpp_grid_connection,
            battery_depth_of_discharge=battery_depth_of_discharge,
            charge_efficiency=charge_efficiency,
            price_H2=price_H2,
            ptg_MW=ptg_MW,
            HSS_kg=HSS_kg,
            storage_eff=storage_eff,
            hhv=hhv,
            m_H2_demand_ts=m_H2_demand_ts_sel,
            H2_storage_t=H2_storage_t_sel,
            penalty_factor_H2=penalty_factor_H2,
            eff_curve=eff_curve,
            min_power_standby=min_power_standby,
            load_min_penalty_factor=load_min_penalty_factor,
            peak_hr_quantile=peak_hr_quantile,
            cost_of_battery_P_fluct_in_peak_price_ratio=cost_of_battery_P_fluct_in_peak_price_ratio,
            n_full_power_hours_expected_per_day_at_peak_price=n_full_power_hours_expected_per_day_at_peak_price,
            electrolyzer_eff_curve_type=electrolyzer_eff_curve_type,
        )

        P_HPP_ts[batch] = P_HPP_ts_batch
        P_curtailment_ts[batch] = P_curtailment_ts_batch
        P_charge_discharge_ts[batch] = P_charge_discharge_ts_batch
        E_SOC_ts[batch] = E_SOC_ts_batch[:-1]
        penalty_ts[batch] = penalty_batch
        P_ptg_ts[batch] = P_ptg_ts_batch
        P_ptg_SB_ts[batch] = P_ptg_SB_ts_batch
        m_H2_ts[batch] = m_H2_ts_batch
        m_H2_offtake_ts[batch] = m_H2_offtake_ts_batch
        LoS_H2_ts[batch] = LoS_H2_ts_batch[:-1]

    E_SOC_ts[-1] = E_SOC_ts[0]
    LoS_H2_ts[-1] = LoS_H2_ts[0]

    return (
        P_HPP_ts,
        P_curtailment_ts,
        P_charge_discharge_ts,
        P_ptg_ts,
        P_ptg_SB_ts,
        E_SOC_ts,
        m_H2_ts,
        m_H2_offtake_ts,
        LoS_H2_ts,
        penalty_ts,
    )


def ems_OR_tools_parts_P2X(
    wind_ts,
    solar_ts,
    price_ts,
    P_batt_MW,
    E_batt_MWh_t,
    hpp_grid_connection,
    battery_depth_of_discharge,
    charge_efficiency,
    price_H2,
    ptg_MW,
    HSS_kg,
    storage_eff,
    hhv,
    m_H2_demand_ts,
    H2_storage_t,
    penalty_factor_H2,
    eff_curve,
    min_power_standby,
    load_min_penalty_factor=1e6,
    peak_hr_quantile=0.9,
    cost_of_battery_P_fluct_in_peak_price_ratio=0.5,
    n_full_power_hours_expected_per_day_at_peak_price=3,
    electrolyzer_eff_curve_type="production",
):
    """EMS solver implemented in or tools

    Parameters
    ----------
    wind_ts : WPP power time series
    solar_ts : PVP power time series
    price_ts : price time series
    P_batt_MW : battery power
    E_batt_MWh_t : battery energy capacity time series
    H2_storage_t : hydrogen storgae capacity time series
    hpp_grid_connection : grid connection
    battery_depth_of_discharge : battery depth of discharge
    charge_efficiency : battery charge efficiency
    peak_hr_quantile : quantile of price time series to define peak price hours
    cost_of_battery_P_fluct_in_peak_price_ratio : cost of battery power fluctuations computed as a peak price ratio
    n_full_power_hours_expected_per_day_at_peak_price : Penalty occurs if number of full power hours expected per day at peak price are not reached
    price_H2: Price of Hydrogen
    ptg_MW: Electrolyzer power capacity
    HSS_kg: Hydrogen storage capacity
    storage_eff: Compressor efficiency for hydrogen storage
    hhv: High heat value
    m_H2_demand_ts: Hydrogen demand times series
    penalty_factor_H2: Penalty on not meeting hydrogen demand in an hour

    Returns
    -------
    P_HPP_ts: HPP power time series
    P_curtailment_ts: HPP curtailed power time series
    P_charge_discharge_ts: Battery charge/discharge power time series
    E_SOC_ts: Battery energy SOC time series
    penalty_ts: penalty time series for not reaching expected energy production at peak hours
    P_ptg_ts: Electrolyzer power consumption time series
    P_ptg_SB_ts: Electrolyzer standby mode power consumption time series
    m_H2_ts: Hydrogen production time series
    m_H2_offtake_ts: Hydrogen offtake time series
    LoS_H2_ts: Level of Hydrogen storage time series

    """

    # Dimensions
    N_t = len(price_ts.index)
    N_days = N_t / 24
    e_peak_day_expected = (
        n_full_power_hours_expected_per_day_at_peak_price * hpp_grid_connection
    )
    e_peak_period_expected = e_peak_day_expected * N_days
    price_peak = np.quantile(price_ts.values, peak_hr_quantile)
    peak_hours_index = np.where(price_ts >= price_peak)[0]

    price_ts_to_max = price_peak - price_ts
    price_ts_to_max.loc[price_ts_to_max < 0] = 0
    price_ts_to_max.iloc[:-1] = (
        0.5 * price_ts_to_max.iloc[:-1].values + 0.5 * price_ts_to_max.iloc[1:].values
    )

    time = price_ts.index
    SOCtime = time.append(pd.Index([time[-1] + pd.Timedelta("1hour")]))

    # Solver OR-Tools (NumVar continu)

    solver = pywraplp.Solver.CreateSolver('GLPK')
    if not solver:
        raise Exception("Solver not created")

    # Continuous Variables
    P_HPP_t = {t: solver.NumVar(0, hpp_grid_connection, f"P_HPP_{t}") for t in time}
    P_curtailment_t = {t: solver.NumVar(0, solver.infinity(), f"P_curt_{t}") for t in time}
    P_charge_discharge = {
        t: solver.NumVar(-P_batt_MW / charge_efficiency, P_batt_MW * charge_efficiency, f"P_batt_{t}")
        for t in time
    }
    E_SOC_t = {t: solver.NumVar(0, solver.infinity(), f"SOC_{t}") for t in SOCtime}
    LoS_H2_t = {t: solver.NumVar(0, solver.infinity(), f"H2_{t}") for t in SOCtime}

    P_ptg_t = {t: solver.NumVar(min_power_standby * ptg_MW, ptg_MW, f"P_ptg_{t}") for t in time}
    m_H2_t = {t: solver.NumVar(0, solver.infinity(), f"H2_prod_{t}") for t in time}
    m_H2_offtake_t = {t: solver.NumVar(0, solver.infinity(), f"H2_offtake_{t}") for t in time}

    penalty = solver.NumVar(0, solver.infinity(), "penalty")
    e_penalty = solver.NumVar(0, solver.infinity(), "e_penalty")

    # Variables for battery power fluctuations penalty
    delta_batt = {t: solver.NumVar(0, solver.infinity(), f'delta_batt_{t}') for t in time[:-1]}

    # Constraints on delta_batt (|P_t+1 - P_t|)
    for i, t in enumerate(time[:-1]):
        tt = time[i+1]
        solver.Add(delta_batt[t] >= P_charge_discharge[tt] - P_charge_discharge[t])
        solver.Add(delta_batt[t] >= P_charge_discharge[t] - P_charge_discharge[tt])

    # Constraints on penalties
    solver.Add(e_penalty >= e_peak_period_expected - solver.Sum([P_HPP_t[time[i]] for i in peak_hours_index]))
    solver.Add(penalty >= price_peak * e_penalty + solver.Sum([penalty_factor_H2 * (m_H2_demand_ts[t] - m_H2_offtake_t[t]) for t in time]))

    # Initial and final conditions
    solver.Add(E_SOC_t[SOCtime[0]] == 0.5 * E_batt_MWh_t[time[0]])
    solver.Add(E_SOC_t[SOCtime[-1]] == 0.5 * E_batt_MWh_t[time[0]])
    solver.Add(LoS_H2_t[SOCtime[0]] == 0)
    solver.Add(LoS_H2_t[SOCtime[-1]] == 0)

    # Electrolyser curves
    if electrolyzer_eff_curve_type == "production":
        x_points = [load * ptg_MW for load, _ in eff_curve]
        y_points = [H2 * ptg_MW for _, H2 in eff_curve]
    elif electrolyzer_eff_curve_type == "efficiency":
        x_points = [load * ptg_MW for load, _ in eff_curve]
        y_points = [load * ptg_MW * eff / hhv * 1000 for load, eff in eff_curve]

    for t in time:

        # Piecewise approximation for electrolyser 
        lambdas_ptg = [solver.NumVar(0, 1, f"lambda_ptg_{t}_{i}") for i in range(len(x_points))]
        solver.Add(solver.Sum(lambdas_ptg) == 1)
        solver.Add(P_ptg_t[t] == solver.Sum([lambdas_ptg[i] * x_points[i] for i in range(len(x_points))]))
        solver.Add(m_H2_t[t] == solver.Sum([lambdas_ptg[i] * y_points[i] for i in range(len(y_points))]))

        # Piecewise linearisation for battery charging or discharging
        x_batt = [-P_batt_MW/charge_efficiency, 0, P_batt_MW*charge_efficiency]
        y_batt = [(-P_batt_MW/charge_efficiency)/charge_efficiency, 0, P_batt_MW*charge_efficiency*charge_efficiency]
        lambdas_batt = [solver.NumVar(0, 1, f"lambda_batt_{t}_{i}") for i in range(len(x_batt))]
        solver.Add(solver.Sum(lambdas_batt) == 1)
        solver.Add(P_charge_discharge[t] == solver.Sum([lambdas_batt[i]*x_batt[i] for i in range(len(x_batt))]))
        tt = t + pd.Timedelta("1h")
        if tt in E_SOC_t:
            solver.Add(E_SOC_t[tt] == E_SOC_t[t] - solver.Sum([lambdas_batt[i]*y_batt[i] for i in range(len(y_batt))]))

        # Piecewise linearisation for H2 storage charging or discharging
        x_H2 = [float(val) for val in [0, HSS_kg]]
        y_H2 = [float(val) for val in [0, HSS_kg*storage_eff]]
        lambdas_H2 = [solver.NumVar(0, 1, f"lambda_H2_{t}_{i}") for i in range(len(x_H2))]
        solver.Add(solver.Sum(lambdas_H2) == 1)
        solver.Add((m_H2_t[t]-m_H2_offtake_t[t]) == solver.Sum([lambdas_H2[i]*x_H2[i] for i in range(len(x_H2))]))
        if tt in LoS_H2_t:
            solver.Add(LoS_H2_t[tt] == LoS_H2_t[t] + solver.Sum([lambdas_H2[i]*y_H2[i] for i in range(len(y_H2))]))

        # SOC and H2 storage limit constraints
        solver.Add(E_SOC_t[t] >= (1 - battery_depth_of_discharge) * E_batt_MWh_t[t])
        solver.Add(E_SOC_t[t] <= E_batt_MWh_t[t])
        solver.Add(LoS_H2_t[t] <= H2_storage_t[t])
        solver.Add(m_H2_offtake_t[t] <= m_H2_demand_ts[t])

        # Balance power constraint
        solver.Add(P_HPP_t[t] == wind_ts[t] + solar_ts[t] - P_curtailment_t[t] + P_charge_discharge[t] - P_ptg_t[t])

    # Objective function
    revenue = solver.Sum([price_ts[t] * P_HPP_t[t] + price_H2 * m_H2_offtake_t[t] for t in time])
    fluct_penalty = solver.Sum([delta_batt[t] * cost_of_battery_P_fluct_in_peak_price_ratio * price_ts_to_max[t] for t in time[:-1]])
    solver.Maximize(revenue - penalty - fluct_penalty)

    status = solver.Solve()

    if status != pywraplp.Solver.OPTIMAL:
        raise Exception("No optimal solution found")

    # Results extraction
    P_HPP_ts = np.array([P_HPP_t[t].solution_value() for t in time])
    P_curtailment_ts = np.array([P_curtailment_t[t].solution_value() for t in time])
    P_charge_discharge_ts = np.array([P_charge_discharge[t].solution_value() for t in time])
    E_SOC_ts = np.array([E_SOC_t[t].solution_value() for t in SOCtime])
    P_ptg_ts = np.array([P_ptg_t[t].solution_value() for t in time])
    m_H2_ts = np.array([m_H2_t[t].solution_value() for t in time])
    LoS_H2_ts = np.array([LoS_H2_t[t].solution_value() for t in SOCtime])
    m_H2_offtake_ts = np.array([m_H2_offtake_t[t].solution_value() for t in time])
    penalty_ts = np.ones(N_t) * (penalty.solution_value() / N_t)

    P_ptg_SB_ts = np.zeros_like(P_ptg_ts)
    for i in range(N_t):
        if abs(P_ptg_ts[i] - min_power_standby * ptg_MW) < 1e-6:
            P_ptg_SB_ts[i] = min_power_standby * ptg_MW
            P_ptg_ts[i] = 0
            m_H2_ts[i] = 0

    return (
        P_HPP_ts,
        P_curtailment_ts,
        P_charge_discharge_ts,
        P_ptg_ts,
        P_ptg_SB_ts,
        E_SOC_ts,
        m_H2_ts,
        m_H2_offtake_ts,
        LoS_H2_ts,
        penalty_ts,
    )
