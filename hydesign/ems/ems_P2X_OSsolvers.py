def ems_ortools_parts_P2X(
    wind_ts,
    solar_ts,
    price_ts,
    P_batt_MW,
    E_batt_MWh_t,
    hpp_grid_connection,
    battery_depth_of_discharge,
    charge_efficiency,
    price_H2,
    ptg_MW,
    HSS_kg,
    storage_eff,
    hhv,
    m_H2_demand_ts,
    H2_storage_t,
    penalty_factor_H2,
    eff_curve,
    min_power_standby,
    load_min_penalty_factor=1e6,
    peak_hr_quantile=0.9,
    cost_of_battery_P_fluct_in_peak_price_ratio=0.5,
    n_full_power_hours_expected_per_day_at_peak_price=3,
    electrolyzer_eff_curve_type="production",
):
    time = price_ts.index
    N_t = len(time)
    N_days = N_t / 24.0
    e_peak_day_expected = (
        n_full_power_hours_expected_per_day_at_peak_price * hpp_grid_connection
    )
    e_peak_period_expected = e_peak_day_expected * N_days
    price_peak = np.quantile(price_ts.values, peak_hr_quantile)
    peak_hours_index = np.where(price_ts.values >= price_peak)[0]

    price_ts_to_max = pd.Series(price_peak - price_ts, index=price_ts.index)
    price_ts_to_max[price_ts_to_max < 0] = 0
    if N_t >= 2:
        sm = 0.5 * price_ts_to_max.values[:-1] + 0.5 * price_ts_to_max.values[1:]
        price_ts_to_max.iloc[:-1] = sm

    solver = pywraplp.Solver.CreateSolver("CBC")
    if solver is None:
        raise RuntimeError("Could not create CBC solver from OR-Tools")

    inf = solver.infinity()
    SOCtime = list(time) + [time[-1] + pd.Timedelta("1hour")]

    # Variables
    P_HPP = {
        t: solver.NumVar(0.0, hpp_grid_connection, f"P_HPP_{i}")
        for i, t in enumerate(time)
    }
    P_curtail = {
        t: solver.NumVar(0.0, hpp_grid_connection, f"Curtail_{i}")
        for i, t in enumerate(time)
    }

    # battery bounds (may be zero)
    P_pos_ub = float(P_batt_MW) * float(charge_efficiency)
    P_neg_ub = (
        float(P_batt_MW) / float(charge_efficiency)
        if float(charge_efficiency) != 0
        else 0.0
    )

    P_pos = {t: solver.NumVar(0.0, P_pos_ub, f"P_pos_{i}") for i, t in enumerate(time)}
    P_neg = {t: solver.NumVar(0.0, P_neg_ub, f"P_neg_{i}") for i, t in enumerate(time)}
    P_batt = {
        t: solver.NumVar(-P_neg_ub, P_pos_ub, f"P_batt_{i}") for i, t in enumerate(time)
    }
    # --- RELAXED: use continuous y in [0,1] instead of binary to avoid infeasibility in degenerate cases
    y_sign = {t: solver.NumVar(0.0, 1.0, f"y_sign_{i}") for i, t in enumerate(time)}

    E_SOC = {t: solver.NumVar(0.0, inf, f"E_SOC_{i}") for i, t in enumerate(SOCtime)}
    LoS_H2 = {t: solver.NumVar(0.0, inf, f"LoS_H2_{i}") for i, t in enumerate(SOCtime)}

    P_ptg = {
        t: solver.NumVar(min_power_standby * ptg_MW, ptg_MW, f"P_ptg_{i}")
        for i, t in enumerate(time)
    }
    m_H2 = {t: solver.NumVar(0.0, inf, f"m_H2_{i}") for i, t in enumerate(time)}
    m_H2_offtake = {
        t: solver.NumVar(0.0, inf, f"m_H2_offtake_{i}") for i, t in enumerate(time)
    }

    e_penalty = solver.NumVar(-inf, inf, "e_penalty")
    e_penalty_pos = solver.NumVar(0.0, inf, "e_penalty_pos")

    abs_delta = {}
    for i in range(N_t - 1):
        abs_delta[i] = solver.NumVar(0.0, inf, f"abs_delta_{i}")

    H2_pos = {t: solver.NumVar(0.0, inf, f"H2_pos_{i}") for i, t in enumerate(time)}
    H2_neg = {t: solver.NumVar(0.0, inf, f"H2_neg_{i}") for i, t in enumerate(time)}

    # Build H2_curve_list and ensure (0,0) exists
    if electrolyzer_eff_curve_type == "production":
        H2_curve_list = [
            (float(load) * float(ptg_MW), float(H2) * float(ptg_MW))
            for load, H2 in eff_curve
        ]
    else:
        H2_curve_list = [
            (
                float(load) * float(ptg_MW),
                float(load) * float(ptg_MW) * float(eff) / float(hhv) * 1000.0,
            )
            for load, eff in eff_curve
        ]

    # Add explicit (0,0) breakpoint if not present (fixes infeasibility when P_ptg can be zero)
    if not any(abs(x) < 1e-9 and abs(y) < 1e-9 for x, y in H2_curve_list):
        H2_curve_list.insert(0, (0.0, 0.0))

    H2_curve_list = sorted(H2_curve_list, key=lambda x: x[0])
    n_break = len(H2_curve_list)
    lambdas = [
        {t: solver.NumVar(0.0, 1.0, f"lambda_{k}_{i}") for i, t in enumerate(time)}
        for k in range(n_break)
    ]

    # Constraints
    for t in time:
        solver.Add(P_batt[t] == P_pos[t] - P_neg[t])
        # Big-M style but with y continuous -> approximate enforcement; avoids infeasibility
        solver.Add(P_pos[t] <= P_pos_ub * y_sign[t])
        solver.Add(P_neg[t] <= P_neg_ub * (1.0 - y_sign[t]))
        solver.Add(P_batt[t] <= P_pos_ub)
        solver.Add(P_batt[t] >= -P_neg_ub)

    for t in time:
        solver.Add(
            P_HPP[t] == wind_ts[t] + solar_ts[t] - P_curtail[t] + P_batt[t] - P_ptg[t]
        )

    solver.Add(E_SOC[SOCtime[0]] == 0.5 * E_batt_MWh_t[time[0]])
    solver.Add(E_SOC[SOCtime[-1]] == 0.5 * E_batt_MWh_t[time[0]])
    solver.Add(LoS_H2[SOCtime[0]] == 0.0)
    solver.Add(LoS_H2[SOCtime[-1]] == 0.0)

    for t in time:
        solver.Add(E_SOC[t] >= (1 - battery_depth_of_discharge) * E_batt_MWh_t[t])
        solver.Add(E_SOC[t] <= E_batt_MWh_t[t])
        solver.Add(P_pos[t] <= P_pos_ub)
        solver.Add(P_neg[t] <= P_neg_ub)
        solver.Add(m_H2_offtake[t] <= m_H2_demand_ts[t])
        solver.Add(LoS_H2[t] <= H2_storage_t[t])
        if H2_storage_t[t] == 0:
            solver.Add(m_H2_offtake[t] == m_H2[t])

    # Electrolyzer piecewise (convex combination). Lambdas sum to 1.
    for i, t in enumerate(time):
        solver.Add(sum(lambdas[k][t] for k in range(n_break)) == 1.0)
        solver.Add(
            P_ptg[t] == sum(lambdas[k][t] * H2_curve_list[k][0] for k in range(n_break))
        )
        solver.Add(
            m_H2[t] == sum(lambdas[k][t] * H2_curve_list[k][1] for k in range(n_break))
        )

    dt = 1.0
    for i, t in enumerate(time):
        tt = SOCtime[i + 1]
        solver.Add(
            E_SOC[tt]
            == E_SOC[t]
            - (charge_efficiency * P_pos[t] - (1.0 / charge_efficiency) * P_neg[t]) * dt
        )

    for i, t in enumerate(time):
        tt = SOCtime[i + 1]
        solver.Add(m_H2[t] - m_H2_offtake[t] == H2_pos[t] - H2_neg[t])
        solver.Add(
            LoS_H2[tt]
            == LoS_H2[t] + storage_eff * H2_pos[t] - (1.0 / storage_eff) * H2_neg[t]
        )

    solver.Add(
        e_penalty
        == e_peak_period_expected - sum(P_HPP[time[i]] for i in peak_hours_index)
    )
    solver.Add(e_penalty_pos >= e_penalty)
    solver.Add(e_penalty_pos >= 0.0)

    for i in range(N_t - 1):
        t = time[i]
        tt = time[i + 1]
        diff = solver.NumVar(-inf, inf, f"diff_{i}")
        solver.Add(diff == P_batt[tt] - P_batt[t])
        solver.Add(abs_delta[i] >= diff)
        solver.Add(abs_delta[i] >= -diff)

    unmet_vars = {t: solver.NumVar(0.0, inf, f"unmet_{i}") for i, t in enumerate(time)}
    for t in time:
        solver.Add(unmet_vars[t] >= m_H2_demand_ts[t] - m_H2_offtake[t])
        solver.Add(unmet_vars[t] >= 0.0)

    # Objective
    objective = solver.Objective()
    for t in time:
        objective.SetCoefficient(P_HPP[t], price_ts[t])
        objective.SetCoefficient(m_H2_offtake[t], price_H2)
    objective.SetCoefficient(e_penalty_pos, -price_peak)
    for t in time:
        objective.SetCoefficient(unmet_vars[t], -penalty_factor_H2)
    for i in range(N_t - 1):
        t = time[i]
        objective.SetCoefficient(
            abs_delta[i],
            -cost_of_battery_P_fluct_in_peak_price_ratio * price_ts_to_max[t],
        )
    objective.SetMaximization()

    # Solve (no integrality since y_sign is continuous)
    status = solver.Solve()
    if status not in (pywraplp.Solver.OPTIMAL, pywraplp.Solver.FEASIBLE):
        raise RuntimeError("Solver failed to find a solution: status=%s" % status)

    P_HPP_ts = np.array([P_HPP[t].solution_value() for t in time])
    P_curtailment_ts = np.array([P_curtail[t].solution_value() for t in time])
    P_charge_discharge_ts = np.array([P_batt[t].solution_value() for t in time])
    E_SOC_ts = np.array([E_SOC[t].solution_value() for t in SOCtime])
    P_ptg_ts = np.array([P_ptg[t].solution_value() for t in time])
    m_H2_ts = np.array([m_H2[t].solution_value() for t in time])
    LoS_H2_ts = np.array([LoS_H2[t].solution_value() for t in SOCtime])
    m_H2_offtake_ts = np.array([m_H2_offtake[t].solution_value() for t in time])

    # Trim LoS_H2 to N_t (drop final SOC)
    LoS_H2_ts = LoS_H2_ts[:-1]

    penalty_val = price_peak * e_penalty_pos.solution_value() + penalty_factor_H2 * sum(
        unmet_vars[t].solution_value() for t in time
    )
    penalty_ts = np.ones(N_t) * (penalty_val / float(N_t))

    P_ptg_SB_ts = np.zeros_like(P_ptg_ts)
    for t_i in range(N_t):
        if abs(P_ptg_ts[t_i] - min_power_standby * ptg_MW) < 1e-6:
            P_ptg_SB_ts[t_i] = min_power_standby * ptg_MW
            P_ptg_ts[t_i] = 0.0
            m_H2_ts[t_i] = 0.0

    return (
        P_HPP_ts,
        P_curtailment_ts,
        P_charge_discharge_ts,
        P_ptg_ts,
        P_ptg_SB_ts,
        E_SOC_ts,
        m_H2_ts,
        m_H2_offtake_ts,
        LoS_H2_ts,
        penalty_ts,
    )


def ems_pyomo_parts_P2X(
    wind_ts,
    solar_ts,
    price_ts,
    P_batt_MW,
    E_batt_MWh_t,
    hpp_grid_connection,
    battery_depth_of_discharge,
    charge_efficiency,
    price_H2,
    ptg_MW,
    HSS_kg,
    storage_eff,
    hhv,
    m_H2_demand_ts,
    H2_storage_t,
    penalty_factor_H2,
    eff_curve,
    min_power_standby,
    load_min_penalty_factor,
    peak_hr_quantile,
    cost_of_battery_P_fluct_in_peak_price_ratio,
    n_full_power_hours_expected_per_day_at_peak_price,
    electrolyzer_eff_curve_type,
):
    """EMS solver implemented in pyomo

    Parameters
    ----------
    wind_ts : WPP power time series
    solar_ts : PVP power time series
    price_ts : price time series
    P_batt_MW : battery power
    E_batt_MWh_t : battery energy capacity time series
    H2_storage_t : hydrogen storgae capacity time series
    hpp_grid_connection : grid connection
    battery_depth_of_discharge : battery depth of discharge
    charge_efficiency : battery charge efficiency
    peak_hr_quantile : quantile of price time series to define peak price hours
    cost_of_battery_P_fluct_in_peak_price_ratio : cost of battery power fluctuations computed as a peak price ratio
    n_full_power_hours_expected_per_day_at_peak_price : Penalty occurs if number of full power hours expected per day at peak price are not reached
    price_H2: Price of Hydrogen
    ptg_MW: Electrolyzer power capacity
    HSS_kg: Hydrogen storage capacity
    storage_eff: Compressor efficiency for hydrogen storage
    ptg_deg: Electrolyzer rate of degradation annually
    hhv: High heat value
    m_H2_demand_ts: Hydrogen demand times series
    penalty_factor_H2: Penalty on not meeting hydrogen demand in an hour

    Returns
    -------
    P_HPP_ts: HPP power time series
    P_curtailment_ts: HPP curtailed power time series
    P_charge_discharge_ts: Battery charge/discharge power time series
    E_SOC_ts: Battery energy SOC time series
    penalty_ts: penalty time series for not reaching expected energy production at peak hours
    P_ptg_ts: Electrolyzer power consumption time series
    P_ptg_SB_ts: Electrolyzer standby mode power consumption time series
    m_H2_ts: Hydrogen production time series
    m_H2_offtake_ts: Hydrogen offtake time series
    LoS_H2_ts: Level of Hydrogen storage time series

    """
    N_t = len(price_ts.index)
    N_days = N_t / 24
    e_peak_day_expected = (
        n_full_power_hours_expected_per_day_at_peak_price * hpp_grid_connection
    )
    e_peak_period_expected = e_peak_day_expected * N_days
    price_peak = np.quantile(price_ts.values, peak_hr_quantile)
    peak_hours_index = np.where(price_ts >= price_peak)[0]

    price_ts_to_max = price_peak - price_ts
    price_ts_to_max.loc[price_ts_to_max < 0] = 0
    price_ts_to_max.iloc[:-1] = (
        0.5 * price_ts_to_max.iloc[:-1].values + 0.5 * price_ts_to_max.iloc[1:].values
    )

    time = price_ts.index
    SOCtime = time.append(pd.Index([time[-1] + pd.Timedelta("1hour")]))

    # for name, series in [("wind", wind_ts), ("solar", solar_ts), ("price", price_ts), ("E_batt", E_batt_MWh_t), ("H2_storage", H2_storage_t)]:
    #     if hasattr(series, "isna"):
    #         print(name, "hasna?", series.isna().any(), "min,max:", series.min(), series.max())
    #     else:
    #         print(name, "type:", type(series))

    model = pyo.ConcreteModel()

    ## Index sets ##
    model.IDX1 = range(len(time))  # time
    model.IDX2 = range(1)  # singleton for penalty vars
    model.IDX3 = [t for t in range(len(time)) if t in peak_hours_index]
    model.IDX4 = range(len(SOCtime))  # soc time (time+1)
    model.IDX5 = range(len(time) - 1)  # time for deltas

    ## Variables ##
    model.P_HPP_t = pyo.Var(
        model.IDX1, domain=pyo.NonNegativeReals, bounds=(0, hpp_grid_connection)
    )
    model.P_curtailment_t = pyo.Var(
        model.IDX1, domain=pyo.NonNegativeReals, bounds=(0, 1e6)
    )

    # Power charge/discharge from battery with Lower/Upper bounds
    model.P_charge_discharge_t = pyo.Var(
        model.IDX1, domain=pyo.Reals, bounds=(-P_batt_MW, P_batt_MW)
    )
    model.P_charge_discharge_with_eff_t = pyo.Var(
        model.IDX1,
        domain=pyo.Reals,
        bounds=(-P_batt_MW / charge_efficiency, P_batt_MW * charge_efficiency),
    )
    model.E_SOC_t = pyo.Var(model.IDX4, domain=pyo.NonNegativeReals)

    # Electrolyser / H2
    model.P_ptg_t = pyo.Var(
        model.IDX1, domain=pyo.NonNegativeReals, bounds=(5.2 + 1e-9, ptg_MW)
    )
    model.m_H2_t = pyo.Var(model.IDX1, domain=pyo.NonNegativeReals, bounds=(0, 1e4))
    model.m_H2_offtake_t = pyo.Var(model.IDX1, domain=pyo.NonNegativeReals)
    model.m_H2_diff = pyo.Var(model.IDX1, domain=pyo.Reals, bounds=(-1e4, 1e4))
    model.m_H2_net_eff = pyo.Var(model.IDX1, domain=pyo.Reals)
    model.LoS_H2_t = pyo.Var(model.IDX4, domain=pyo.NonNegativeReals)

    # Battery delta for battery operation constraints
    model.P_battery_delta = pyo.Var(model.IDX5, domain=pyo.Reals, bounds=(-1e6, 1e6))
    model.P_battery_delta_abs_pw = pyo.Var(
        model.IDX5, domain=pyo.Reals, bounds=(0, 1e6)
    )

    # Penalties
    model.penalty = pyo.Var(model.IDX2, domain=pyo.Reals, bounds=(-1e6, 1e6))
    model.e_penalty = pyo.Var(model.IDX2, domain=pyo.Reals, bounds=(-1e6, 1e6))

    ## Constraints ##
    model.power_constraint = pyo.ConstraintList()
    model.battery_dynamics_constraint = pyo.ConstraintList()
    model.h2_dynamics_constraint = pyo.ConstraintList()
    model.soc_constraints = pyo.ConstraintList()
    model.h2_constraints = pyo.ConstraintList()
    model.penalty_constraint = pyo.ConstraintList()

    # Initial / final SOC
    model.soc_constraints.add(model.E_SOC_t[0] == 0.5 * E_batt_MWh_t.iloc[0])
    # model.soc_constraints.add(model.E_SOC_t[len(SOCtime) - 1] == 0.5 * E_batt_MWh_t.iloc[0])

    # Initial / final H2
    model.h2_constraints.add(model.LoS_H2_t[0] == 0)
    # model.h2_constraints.add(model.LoS_H2_t[len(SOCtime) - 1] == 0)

    # Penalty constraints
    model.penalty_constraint.add(
        model.e_penalty[0]
        == (e_peak_period_expected - sum(model.P_HPP_t[t] for t in model.IDX3))
    )

    model.penalty_constraint_pw = pyo.Piecewise(
        model.IDX2,
        model.penalty,
        model.e_penalty,
        pw_pts=[-1e6, 0, 1e6],
        f_rule=[0, 0, price_peak * 1e6],
        pw_constr_type="EQ",
        pw_repn="DLOG",
        force_pw=False,
        warn_domain_coverage=False,
    )

    # Charge/discharge constraint
    model.battery_eff_constraint = pyo.Piecewise(
        model.IDX1,
        model.P_charge_discharge_with_eff_t,
        model.P_charge_discharge_t,
        pw_pts=[-P_batt_MW, 0, P_batt_MW],
        f_rule=[-P_batt_MW / charge_efficiency, 0, P_batt_MW * charge_efficiency],
        pw_constr_type="EQ",
        pw_repn="DLOG",
        force_pw=False,
        warn_domain_coverage=False,
        unbounded_domain_var=True,
    )

    for t in model.IDX1:
        model.h2_constraints.add(
            model.m_H2_diff[t] == model.m_H2_t[t] - model.m_H2_offtake_t[t]
        )

    # Piecewise linear mapping: f3(x) = storage_eff * x
    epsilon = 1e-6
    model.h2_storage_eff_constraint = pyo.Piecewise(
        model.IDX1,
        model.m_H2_net_eff,
        model.m_H2_diff,
        pw_pts=[-1e4, -epsilon, epsilon, 1e4],
        f_rule=[
            -1e4 / storage_eff,
            -epsilon / storage_eff,
            epsilon * storage_eff,
            1e4 * storage_eff,
        ],
        pw_constr_type="EQ",
        pw_repn="CC",
        warn_domain_coverage=False,
        unbounded_domain_var=False,
    )

    # Caclulating electrolyzer efficiency as a function of load (piecewise linear approximation)
    if electrolyzer_eff_curve_type == "production":
        H2_curve_list = [(load * ptg_MW, H2 * ptg_MW) for load, H2 in eff_curve]
    elif electrolyzer_eff_curve_type == "efficiency":
        H2_curve_list = [
            (load * ptg_MW, load * ptg_MW * efficiency / hhv * 1000)
            for load, efficiency in eff_curve
        ]
    else:
        raise ValueError(
            f'electrolyzer_eff_curve_type is: "{electrolyzer_eff_curve_type}". Available options are ["production", "efficiency"]'
        )

    # Electrolyzer production curve (piecewise)
    H2_curve_x = [pt[0] for pt in H2_curve_list]
    H2_curve_y = [pt[1] for pt in H2_curve_list]
    model.H2_prod_constraint = pyo.Piecewise(
        model.IDX1,
        model.m_H2_t,
        model.P_ptg_t,
        pw_pts=H2_curve_x,
        f_rule=H2_curve_y,
        pw_constr_type="EQ",
        pw_repn="DLOG",
    )

    # Dynamics
    for t in model.IDX1:
        tt = t + 1
        if tt < len(SOCtime):
            # Battery dynamics
            model.battery_dynamics_constraint.add(
                model.E_SOC_t[tt]
                == model.E_SOC_t[t] - model.P_charge_discharge_with_eff_t[t]
            )
            # Hydrogen dynamics
            model.h2_dynamics_constraint.add(
                model.LoS_H2_t[tt] == model.LoS_H2_t[t] + model.m_H2_net_eff[t]
            )

        # Power balance
        model.power_constraint.add(
            model.P_HPP_t[t]
            == wind_ts.iloc[t]
            + solar_ts.iloc[t]
            - model.P_curtailment_t[t]
            + model.P_charge_discharge_with_eff_t[t]
            - model.P_ptg_t[t]
        )

        # Battery limits
        model.soc_constraints.add(model.E_SOC_t[t] <= E_batt_MWh_t.iloc[t])
        model.soc_constraints.add(
            model.E_SOC_t[t] >= (1 - battery_depth_of_discharge) * E_batt_MWh_t.iloc[t]
        )

        # H2 storage and demand limits
        model.h2_constraints.add(model.LoS_H2_t[t] <= H2_storage_t.iloc[t])
        model.h2_constraints.add(model.m_H2_offtake_t[t] <= m_H2_demand_ts.iloc[t])

        # If storage = 0, then direct offtake = production
        if H2_storage_t.iloc[t] == 0:
            model.h2_constraints.add(model.m_H2_offtake_t[t] == model.m_H2_t[t])

    for t in model.IDX5:
        model.power_constraint.add(
            model.P_battery_delta[t]
            == model.P_charge_discharge_with_eff_t[t + 1]
            - model.P_charge_discharge_with_eff_t[t]
        )

    model.P_battery_delta_abs_pw_constr = pyo.Piecewise(
        model.IDX5,
        model.P_battery_delta_abs_pw,
        model.P_battery_delta,
        pw_pts=[-1e6, 0, 1e6],
        f_rule=[1e6, 0, 1e6],
        pw_constr_type="EQ",
        pw_repn="DLOG",
        force_pw=False,
        warn_domain_coverage=False,
    )

    ## Objective ##
    model.OBJ = pyo.Objective(
        expr=(
            sum(
                price_ts.iloc[t] * model.P_HPP_t[t] + price_H2 * model.m_H2_offtake_t[t]
                for t in model.IDX1
            )
            - model.penalty[0]
            - sum(
                penalty_factor_H2 * (m_H2_demand_ts.iloc[t] - model.m_H2_offtake_t[t])
                for t in model.IDX1
            )
            - sum(
                model.P_battery_delta_abs_pw[t]
                * cost_of_battery_P_fluct_in_peak_price_ratio
                * price_ts_to_max.iloc[t]
                for t in model.IDX5
            )
        ),
        sense=pyo.maximize,
    )

    # opt = pyo.SolverFactory('scip', executable=r"C:\Program Files\SCIPOptSuite_9.2.3\bin\scip.exe")
    # opt = pyo.SolverFactory('cbc', executable=r"C:\Users\s223344\AppData\Local\anaconda3\envs\hydesign\Library\bin\cbc.exe")
    opt = pyo.SolverFactory("glpk")
    # opt = pyo.SolverFactory('cplex')
    # opt = pyo.SolverFactory('highs')

    results = opt.solve(model, tee=True)

    P_HPP_ts_df = pd.Series(
        [pyo.value(model.P_HPP_t[t]) for t in model.IDX1], index=time
    )

    P_curtailment_ts_df = pd.Series(
        [pyo.value(model.P_curtailment_t[t]) for t in model.IDX1], index=time
    )

    P_charge_discharge_ts_df = pd.Series(
        [pyo.value(model.P_charge_discharge_t[t]) for t in model.IDX1], index=time
    )

    E_SOC_ts_df = pd.Series(
        [pyo.value(model.E_SOC_t[t]) for t in model.IDX4], index=SOCtime
    )

    P_ptg_ts_df = pd.Series(
        [pyo.value(model.P_ptg_t[t]) for t in model.IDX1], index=time
    )

    m_H2_ts_df = pd.Series([pyo.value(model.m_H2_t[t]) for t in model.IDX1], index=time)

    LoS_H2_ts_df = pd.Series(
        [pyo.value(model.LoS_H2_t[t]) for t in model.IDX4], index=SOCtime
    )

    m_H2_offtake_ts_df = pd.Series(
        [pyo.value(model.m_H2_offtake_t[t]) for t in model.IDX1], index=time
    )

    # make a time series like P_HPP with a constant penalty
    penalty_value = pyo.value(model.penalty[0])
    penalty_ts = np.ones(N_t) * (penalty_value / N_t)

    P_HPP_ts = P_HPP_ts_df.reindex(time, fill_value=0).values
    P_curtailment_ts = P_curtailment_ts_df.reindex(time, fill_value=0).values
    P_charge_discharge_ts = P_charge_discharge_ts_df.reindex(time, fill_value=0).values
    E_SOC_ts = E_SOC_ts_df.reindex(SOCtime, fill_value=0).values
    P_ptg_ts = P_ptg_ts_df.reindex(time, fill_value=0).values
    m_H2_ts = m_H2_ts_df.reindex(time, fill_value=0).values
    LoS_H2_ts = LoS_H2_ts_df.reindex(time, fill_value=0).values
    m_H2_offtake_ts = m_H2_offtake_ts_df.reindex(time, fill_value=0).values

    if len(P_HPP_ts_df) < len(wind_ts):
        # print('recomputing p_hpp')
        P_HPP_ts = (
            wind_ts.values
            + solar_ts.values
            + -P_curtailment_ts
            + P_charge_discharge_ts
            - P_ptg_ts
        )
    P_ptg_SB_ts = np.zeros_like(P_ptg_ts)
    for t in range(N_t):
        if abs(P_ptg_ts[t] - min_power_standby * ptg_MW) < 1e-6:
            P_ptg_SB_ts[t] = min_power_standby * ptg_MW
            P_ptg_ts[t] = 0
            m_H2_ts[t] = 0

    return (
        P_HPP_ts,
        P_curtailment_ts,
        P_charge_discharge_ts,
        P_ptg_ts,
        P_ptg_SB_ts,
        E_SOC_ts,
        m_H2_ts,
        m_H2_offtake_ts,
        LoS_H2_ts,
        penalty_ts,
    )


class ems_long_term_operation_p2x:
    """Pure Python Long term operation EMS. Predicts the operation of the plant throughout the entire lifetime, taking into account the battery, wind, p2g
    and PV degradations.

    Parameters
    ----------
    ii_time : indices on the liftime timeseries. Hydesign operates in each range at constant battery health.
    SoH : Battery state of health at discretization levels
    wind_t_ext_deg : WPP power time series with degradation [MW]
    solar_t_ext_deg : WPP power time series with degradation [MW]
    wind_t_ext : WPP power time series [MW]
    solar_t_ext : PVP power time series [MW]
    price_t_ext : Electricity price time series
    b_P : Battery power capacity
    b_E : Battery energy storage capacity
    G_MW : Grid capacity
    battery_depth_of_discharge : battery depth of discharge
    battery_charge_efficiency : battery charge efficiency
    hpp_curt_t : HPP curtailed power time series
    b_t : Battery charge/discharge power time series
    b_E_SOC_t : Battery energy SOC time series
    peak_hr_quantile : Quantile of price time series to define peak price hours
    n_full_power_hours_expected_per_day_at_peak_price : Penalty occurs if number of full power hours expected per day at peak price are not reached

    Returns
    -------
    hpp_t_with_deg : HPP power time series
    hpp_curt_t_with_deg : HPP curtailed power time series
    b_t_with_deg : Battery charge/discharge power time series
    b_E_SOC_t_with_deg : Battery energy SOC time series
    penalty_t_with_deg : penalty for not reaching expected energy production at peak hours
    total_curtailment : total curtailment in the lifetime
    """

    def __init__(
        self,
        N_time,
        num_batteries=1,
        life_y=25,
        intervals_per_hour=1,
        ems_type="energy_penalty",
        load_min_penalty_factor=1e6,
        eff_curve=None,
        electrolyzer_eff_curve_type="production",
        hhv=39.3,
        ptg_deg_yr=None,
        ptg_deg_profile=None,
    ):

        self.N_time = N_time
        self.intervals_per_hour = intervals_per_hour
        self.life_y = life_y
        self.life_h = 365 * 24 * life_y
        self.life_intervals = self.life_h * intervals_per_hour
        self.ems_type = ems_type
        self.load_min_penalty_factor = load_min_penalty_factor
        self.eff_curve = eff_curve
        self.electrolyzer_eff_curve_type = electrolyzer_eff_curve_type
        self.hhv = hhv
        self.ptg_deg_yr = ptg_deg_yr
        self.ptg_deg_profile = ptg_deg_profile

    def compute(
        self,
        SoH,
        wind_t_ext_deg,
        solar_t_ext_deg,
        wind_t_ext,
        solar_t_ext,
        price_t_ext,
        b_E,
        G_MW,
        battery_depth_of_discharge,
        battery_charge_efficiency,
        hpp_curt_t,
        b_t,
        b_E_SOC_t,
        peak_hr_quantile,
        n_full_power_hours_expected_per_day_at_peak_price,
        P_ptg_t,
        m_H2_t,
        m_H2_offtake_t,
        ptg_MW,
    ):

        if self.ems_type == "energy_penalty":
            ems_longterm = self.operation_solar_batt_deg_p2x
        else:
            raise Warning("This class should only be used for energy_penalty")

        if self.intervals_per_hour == 1:
            freq = "1h"
        else:
            freq = f"{60 / self.intervals_per_hour:.0f}min"

        args = dict(
            wind_t_deg=wind_t_ext_deg,
            solar_t_deg=solar_t_ext_deg,
            batt_degradation=SoH,
            wind_t=wind_t_ext,
            solar_t=solar_t_ext,
            hpp_curt_t=hpp_curt_t,
            b_t=b_t,
            b_E_SOC_t=b_E_SOC_t,
            G_MW=float(G_MW),
            b_E=float(b_E),
            battery_depth_of_discharge=float(battery_depth_of_discharge),
            battery_charge_efficiency=float(battery_charge_efficiency),
            b_E_SOC_0=None,
            price_ts=price_t_ext,
            peak_hr_quantile=peak_hr_quantile,
            n_full_power_hours_expected_per_day_at_peak_price=n_full_power_hours_expected_per_day_at_peak_price,
            freq=freq,
            P_ptg_t=P_ptg_t,
            m_H2_t=m_H2_t,
            m_H2_offtake_t=m_H2_offtake_t,
            ptg_MW=ptg_MW,
        )

        (
            Hpp_deg,
            P_curt_deg,
            b_t_sat,
            b_E_SOC_t_sat,
            penalty_t_with_deg,
            p_ptg_deg,
            m_H2_t_deg,
            m_H2_offtake_t_deg,
        ) = ems_longterm(**args)

        hpp_t_with_deg = Hpp_deg
        hpp_curt_t_with_deg = P_curt_deg
        b_t_with_deg = b_t_sat
        b_E_SOC_t_with_deg = b_E_SOC_t_sat
        penalty_t_with_deg = penalty_t_with_deg
        total_curtailment_with_deg = P_curt_deg.sum()
        total_curtailment = hpp_curt_t.sum()
        return (
            hpp_t_with_deg,
            hpp_curt_t_with_deg,
            b_t_with_deg,
            b_E_SOC_t_with_deg,
            penalty_t_with_deg,
            total_curtailment_with_deg,
            total_curtailment,
            p_ptg_deg,
            m_H2_t_deg,
            m_H2_offtake_t_deg,
        )

    def operation_solar_batt_deg_p2x(
        self,
        wind_t_deg,
        solar_t_deg,
        batt_degradation,
        wind_t,  #  this method is not using wind_t
        solar_t,  #  this method is not using solar_t
        hpp_curt_t,
        b_t,
        b_E_SOC_t,
        G_MW,
        b_E,
        battery_depth_of_discharge,
        battery_charge_efficiency,
        price_ts,
        b_E_SOC_0=None,
        peak_hr_quantile=0.9,
        n_full_power_hours_expected_per_day_at_peak_price=3,
        freq="1h",
        P_ptg_t=None,
        m_H2_t=None,
        m_H2_offtake_t=None,
        ptg_MW=None,
    ):
        """EMS operation for degraded PV and battery based on an existing EMS.

        Parameters
        ----------
        wind_t_deg: Wind time series including degradation
        solar_t_deg: PV time series including degradation
        batt_degradation: Battery degradation as health factor [0=dead,1=new]
        wind_t: WPP power time series
        solar_t: PVP power time series
        hpp_curt_t: HPP curtailment time series results form an EMS planed without degradation
        b_t: HPP battery power (charge/discharge) time series results form an EMS planed without degradation
        b_E_SOC_t: HPP battery state of charge (SoC) time series results form an EMS planed without degradation
        b_E_SOC_0: Initial charge status of the actual operation
        price_ts : price time series
        G_MW : grid connection
        E_batt_MWh_t : battery energy capacity time series
        battery_depth_of_discharge : battery depth of discharge
        battery_charge_efficiency : battery charge efficiency
        peak_hr_quantile : quantile of price time series to define peak price hours
        cost_of_battery_P_fluct_in_peak_price_ratio : cost of battery power fluctuations computed as a peak price ratio
        n_full_power_hours_expected_per_day_at_peak_price : Penalty occurs if number of full power hours expected per day at peak price are not reached

        Returns
        -------
        Hpp_deg : HPP power time series
        P_curt_deg : HPP curtailed power time series
        b_t_sat : Battery charge/discharge power time series
        b_E_SOC_t_sat : Battery energy SOC time series
        penalty_ts : penalty for not reaching expected energy production at peak hours
        """
        B_p = np.max(np.abs(b_t))

        wind_solar_t_deg = solar_t_deg + wind_t_deg

        b_t_less_sol = b_t.copy()
        dt = 1

        # Reduction in power to battery due to reduction of solar
        for i in range(len(b_t)):
            if b_t[i] < 0:

                # Try to follow SoC to the maximum
                if -b_t[i] > wind_solar_t_deg[i]:
                    b_t_less_sol[i] = -wind_solar_t_deg[i]

                b_t_less_sol[i] = np.clip(b_t_less_sol[i], -B_p, B_p)

        # Initialize the SoC
        b_E_SOC_t_sat = b_E_SOC_t.copy()
        if b_E_SOC_0 == None:
            try:
                b_E_SOC_t_sat[0] = b_E_SOC_t[0]
            except:
                raise ("len(b_E_SOC_t):", len(b_E_SOC_t))
        else:
            b_E_SOC_t_sat[0] = b_E_SOC_0

        # Update the SoC
        for i in range(len(b_t_less_sol)):
            if b_t_less_sol[i] < 0:  # charging
                b_E_SOC_t_sat[i + 1] = (
                    b_E_SOC_t_sat[i] - b_t_less_sol[i] * dt * battery_charge_efficiency
                )
            if b_t_less_sol[i] >= 0:  # discharging
                b_E_SOC_t_sat[i + 1] = (
                    b_E_SOC_t_sat[i] - b_t_less_sol[i] * dt / battery_charge_efficiency
                )

            b_E_SOC_t_sat[i + 1] = np.clip(
                b_E_SOC_t_sat[i + 1],
                (1 - battery_depth_of_discharge) * b_E * batt_degradation[i],
                b_E * batt_degradation[i],
            )

        # Recompute the battery power
        b_t_sat = b_t.copy()
        for i in range(len(b_t_sat)):
            if b_t[i] < 0:
                b_t_sat[i] = (
                    (b_E_SOC_t_sat[i] - b_E_SOC_t_sat[i + 1])
                    / battery_charge_efficiency
                ) / dt
            elif b_t[i] >= 0:
                b_t_sat[i] = (
                    (b_E_SOC_t_sat[i] - b_E_SOC_t_sat[i + 1])
                    * battery_charge_efficiency
                ) / dt

        # Hpp_deg = np.minimum( wind_t_deg + solar_t_deg + b_t_sat, G_MW)
        # prod_red = (wind_t + solar_t + b_t) - (wind_t_deg + solar_t_deg + b_t_sat)
        # H2_to_grid_ratio = np.nan_to_num(P_ptg / (P_ptg + P_hpp)
        # First see if production reduction can be covered by reducing curtailment:
        # P_curt_deg = np.minimum(0, P_curt - prod_red)
        # Try propotionally changing degraded variables:
        f_ptg = np.nan_to_num(P_ptg_t / (wind_t + solar_t + b_t))
        # f_grid = np.nan_to_num(p_grid / (wind_t + solar_t + b_t))

        p_ptg_deg = f_ptg * (wind_t_deg + solar_t_deg + b_t_sat)
        if self.electrolyzer_eff_curve_type == "production":
            H2_curve_list = [
                (load * ptg_MW, H2 * ptg_MW) for load, H2 in self.eff_curve
            ]
        elif self.electrolyzer_eff_curve_type == "efficiency":
            H2_curve_list = [
                (load * ptg_MW, load * ptg_MW * efficiency / self.hhv * 1000)
                for load, efficiency in self.eff_curve
            ]
        else:
            raise ValueError(
                f'electrolyzer_eff_curve_type is: "{self.electrolyzer_eff_curve_type}". Available options are ["production", "efficiency"]'
            )

        # take into account p2x degradation
        t_over_year = np.arange(self.life_intervals) / (
            365 * 24 * self.intervals_per_hour
        )
        degradation = np.interp(t_over_year, self.ptg_deg_yr, self.ptg_deg_profile)
        factor = 1 - degradation

        m_H2_t_deg = factor * np.interp(
            p_ptg_deg,
            np.ravel([x[0] for x in H2_curve_list]),
            np.ravel([x[1] for x in H2_curve_list]),
            left=0,
            right=0,
        )
        m_H2_offtake_t_deg = np.nan_to_num(m_H2_offtake_t / m_H2_t) * m_H2_t_deg
        # p_grid_deg = f_grid * (wind_t_deg + solar_t_deg + b_t_sat)
        # f_ptg = p_ptg / (wind_t + solar_t + b_t)

        Hpp_deg = np.minimum(wind_t_deg + solar_t_deg + b_t_sat - p_ptg_deg, G_MW)
        P_curt_deg = np.maximum(
            wind_t_deg + solar_t_deg + b_t_sat - p_ptg_deg - G_MW, 0
        )

        # Compute penalty per week
        H_df = pd.DataFrame(
            np.copy(Hpp_deg),
            columns=["hpp_t_with_deg"],
            index=pd.date_range(
                start="01-01-1991 00:00",
                periods=len(Hpp_deg),
                freq=freq,
            ),
        )
        H_df["price_t_ext"] = price_ts
        price_peak = float(np.quantile(H_df["price_t_ext"], peak_hr_quantile))
        H_df["peak"] = H_df["price_t_ext"] >= price_peak
        H_df.loc[~H_df["peak"], "hpp_t_with_deg"] = 0

        N_days = 7
        H_df_week = H_df.resample(f"{N_days}d").sum()

        e_peak_day_expected = float(
            n_full_power_hours_expected_per_day_at_peak_price * G_MW
        )
        e_peak_period_expected = e_peak_day_expected * N_days

        H_df_week["e_peak_period_expected"] = float(e_peak_period_expected)
        H_df_week["e_penalty"] = (
            H_df_week["e_peak_period_expected"] - H_df_week["hpp_t_with_deg"]
        )
        H_df_week["penalty"] = price_peak * np.maximum(0, H_df_week["e_penalty"])

        penalty_df = H_df_week["penalty"].reindex_like(H_df).fillna(0.0)
        penalty_ts = penalty_df.values.flatten()

        return (
            Hpp_deg,
            P_curt_deg,
            b_t_sat,
            b_E_SOC_t_sat,
            penalty_ts,
            p_ptg_deg,
            m_H2_t_deg,
            m_H2_offtake_t_deg,
        )


